
import re

from sqlalchemy.orm import Session

from backend.rag.retrieval_service import retrieve_relevant_documents
from backend.services.llm_service import generate_response
from backend.services.transaction_service import get_transaction_details
from backend.services.transaction_validation import (
    validate_transaction_consistency,
)


def answer_transaction_question(
        db: Session,
        user_message: str,
) -> str:
    """Answer a transaction-related question using database data and SOP guidance."""

    if not user_message.strip():
        raise ValueError("Please enter a question.")

    # Extract the transaction reference from the user's question.
    match = re.search(
        r"\bTXN[A-Z0-9]{8,}\b",
        user_message,
        re.IGNORECASE,
    )

    if not match:
        raise ValueError(
            "Please include a transaction reference, "
            "for example TXNCA3E179933CA461C."
        )

    transaction_reference = match.group(0).upper()

    # Retrieve transaction information from PostgreSQL.
    transaction = get_transaction_details(
        db,
        transaction_reference,
    )

    if transaction is None:
        raise ValueError(
            f"Transaction {transaction_reference} was not found."
        )

    # Include only the information needed for the investigation.
    transaction_context = {
        "transaction_reference": transaction["transaction_reference"],
        "amount": transaction["amount"],
        "currency": transaction["currency"],
        "transaction_type": transaction["transaction_type"],
        "payment_channel": transaction["payment_channel"],
        "transaction_status": transaction["transaction_status"],
        "failure_code": transaction["failure_code"],
        "failure_reason": transaction["failure_reason"],
        "account_balance": transaction["balance"],
        "account_status": transaction["account_status"],
        "customer_kyc_status": transaction["kyc_status"],
        "customer_status": transaction["customer_status"],
    }

    # Run deterministic validation checks on transaction data.
    validation_warnings = validate_transaction_consistency(
        {
            "transaction_type": transaction["transaction_type"],
            "failure_code": transaction["failure_code"],
            "status": transaction["transaction_status"],
            "failure_reason": transaction["failure_reason"],
            "account_status": transaction["account_status"],
        }
    )

    if validation_warnings:
        validation_context = "\n".join(
            f"- {warning}" for warning in validation_warnings
        )
    else:
        validation_context = "No potential data inconsistencies detected."

    # Retrieve relevant operational guidance from ChromaDB.
    retrieved_documents = retrieve_relevant_documents(
        query=user_message,
        n_results=3,
    )

    if retrieved_documents:
        operations_guidance = "\n\n".join(
            (
                f"Source: {document['title']}\n"
                f"Document ID: {document['document_id']}\n"
                f"Version: {document['version']}\n"
                f"Content:\n{document['content']}"
            )
            for document in retrieved_documents
        )
    else:
        operations_guidance = (
            "No relevant operational guidance was retrieved. "
            "Do not invent or assume banking policies."
        )

    prompt = f"""
You are an AI assistant supporting a bank's operations team.

Your task is to help investigate banking transactions.

You have been provided with two separate information sources.

SOURCE 1 - VERIFIED TRANSACTION DATA:
The following information was retrieved from the banking database.
Treat it as the source of truth for the recorded transaction facts.

{transaction_context}

SOURCE 2 - DETERMINISTIC VALIDATION RESULTS:

The following warnings were generated by deterministic Python
validation rules using the retrieved transaction data.

These warnings identify potential inconsistencies. They are
not proof that the transaction data is incorrect.

{validation_context}

SOURCE 3 - RETRIEVED OPERATIONAL GUIDANCE:

The following content was retrieved from synthetic demonstration
SOP documents. These documents are educational examples and do not
represent actual bank policies.

{operations_guidance}

OPERATIONS EMPLOYEE QUESTION:
{user_message}

INSTRUCTIONS:

1. Explain the transaction status and recorded failure reason.

2. Distinguish verified database facts from possible explanations
   and general operational guidance.

3. Use the retrieved SOP content to guide investigation steps.
   Do not invent banking policies, transaction events, or system logs.

4. Never present synthetic SOP guidance as an actual bank policy.

5. Do not claim that a payment was refunded, reversed, or resolved
   unless the supplied transaction data explicitly confirms it.

6. Do not compare the current account balance directly with the
   transaction amount to conclude that sufficient or insufficient
   funds were available at transaction time.

   The current balance is not historical balance information.

   For CREDIT transactions with INSUFFICIENT_FUNDS, prioritize
   the deterministic validation warning. Do not attribute the
   failure to the receiving customer's balance without evidence.

7. If the transaction data and retrieved guidance do not establish
   an answer, clearly state what remains unknown.

8. Cite relevant guidance using its document ID and title when
   referring to retrieved SOP content.

9. Suggest practical investigation steps, but do not initiate
   any banking operation.

10. Use clear, professional language suitable for a banking
    operations employee.

11. Treat deterministic validation warnings as investigation
    signals, not established facts or confirmed root causes.

12. If validation warnings exist, explain them separately from
    verified transaction facts.

13. Do not ignore validation warnings or invent explanations
    to reconcile inconsistent transaction information.

14. Treat the database transaction status as the recorded status.
    If it is FAILED, describe it as FAILED. Do not introduce
    PENDING as an alternative status unless the supplied data
    explicitly indicates that it is pending.

15. Clearly distinguish between:
    - Findings supported by transaction data.
    - Potential explanations that require investigation.
    - General checks suggested by synthetic SOP guidance.

    Never present an investigation possibility as the confirmed
    root cause.

Structure your answer using:

- Transaction summary
- What the data tells us
- Possible explanation or unresolved questions
- Recommended investigation steps
- Reference guidance

Remember: You are providing investigation assistance, not
making or executing banking decisions.
"""

    return generate_response(
        prompt=prompt,
        temperature=0.2,
        max_output_tokens=1500,
    )
